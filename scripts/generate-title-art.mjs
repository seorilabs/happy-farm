import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = ['title-background.jpg', 'title-shade.png'];
const nativeDir = path.join(root, 'apps/mobile/src/art/assets');
const sources = {};
for (const file of files) {
  const bytes = fs.readFileSync(path.join(root, 'assets/art', file));
  const mime = file.endsWith('.jpg') ? 'image/jpeg' : 'image/png';
  sources[file === files[0] ? 'background' : 'shade'] = { uri: `data:${mime};base64,${bytes.toString('base64')}` };
  const target = path.join(nativeDir, file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || !bytes.equals(fs.readFileSync(target))) throw new Error(`Native title art differs: ${file}`);
  } else {
    fs.writeFileSync(target, bytes);
  }
}
const target = path.join(root, 'apps/ait/src/farm/platform/titleArt.generated.ts');
const output = `// Generated by scripts/generate-title-art.mjs. Source: assets/art/title-*\nimport type { FarmTitleArt } from '../../../../../packages/farm-ui/src';\n\nexport const appsInTossTitleArt: FarmTitleArt = ${JSON.stringify(sources)};\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('AIT title art differs from its source');
} else {
  fs.writeFileSync(target, output);
}
console.log('Title art: native files and AIT embedded images match their sources.');
