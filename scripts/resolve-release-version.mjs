#!/usr/bin/env node
import { appendFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const GOOGLE_PLAY_MAX_VERSION_CODE = 2100000000;
const VERSION_SEGMENT_BASE = 1000;
const RELEASE_TAG_PATTERN = /^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;

function parseArgs(argv) {
  const args = new Map();

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];

    if (arg === '--') {
      continue;
    }

    if (!arg.startsWith('--')) {
      throw new Error(`Unexpected argument: ${arg}`);
    }

    const key = arg.slice(2);
    if (key === 'github-output' || key === 'github-step-summary' || key === 'quiet' || key === 'write-release-info') {
      args.set(key, true);
      continue;
    }

    const value = argv[index + 1];
    if (value == null || value.startsWith('--')) {
      throw new Error(`Missing value for --${key}`);
    }

    args.set(key, value);
    index += 1;
  }

  return args;
}

function readInteger(value, label, { min, max }) {
  if (value == null || value === '') {
    throw new Error(`${label} is required.`);
  }

  if (!/^[0-9]+$/.test(value)) {
    throw new Error(`${label} must be an integer, got: ${value}`);
  }

  const parsedValue = Number(value);
  if (!Number.isSafeInteger(parsedValue) || parsedValue < min || (max != null && parsedValue > max)) {
    throw new Error(`${label} must be between ${min} and ${max ?? 'safe integer max'}, got: ${value}`);
  }

  return parsedValue;
}

function readReleaseTag(args) {
  const tag = args.get('tag') ?? process.env.RELEASE_TAG ?? process.env.GITHUB_REF_NAME;

  if (tag == null || tag === '') {
    throw new Error('Release tag is required. Use --tag v1.2.3 or run from a vX.Y.Z git tag.');
  }

  return tag;
}

function parseReleaseTag(tag) {
  const match = RELEASE_TAG_PATTERN.exec(tag);
  if (match == null) {
    throw new Error(`Release tag must use vX.Y.Z numeric SemVer format, got: ${tag}`);
  }

  return {
    releaseTag: tag,
    major: readInteger(match[1], 'major', { min: 1 }),
    minor: readInteger(match[2], 'minor', { min: 0, max: VERSION_SEGMENT_BASE - 1 }),
    patch: readInteger(match[3], 'patch', { min: 0, max: VERSION_SEGMENT_BASE - 1 }),
  };
}

function resolveReleaseVersion(args) {
  const { releaseTag, major, minor, patch } = parseReleaseTag(readReleaseTag(args));

  const buildNumber = major * 1_000_000 + minor * VERSION_SEGMENT_BASE + patch;
  if (buildNumber > GOOGLE_PLAY_MAX_VERSION_CODE) {
    throw new Error(`build_number exceeds Google Play versionCode maximum: ${buildNumber}`);
  }

  const versionName = `${major}.${minor}.${patch}`;

  return {
    release_tag: releaseTag,
    version_name: versionName,
    release_major: String(major),
    release_minor: String(minor),
    release_patch: String(patch),
    build_number: String(buildNumber),
    google_play_version_code: String(buildNumber),
    google_play_fallback_version_code: String(buildNumber),
    apple_marketing_version: versionName,
    apple_build_number: String(buildNumber),
  };
}

function writeGithubOutput(values) {
  const outputPath = process.env.GITHUB_OUTPUT;
  if (outputPath == null || outputPath === '') {
    throw new Error('GITHUB_OUTPUT is required when --github-output is set.');
  }

  const output = Object.entries(values)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n');
  appendFileSync(outputPath, `${output}\n`);
}

function writeGithubStepSummary(values) {
  const summaryPath = process.env.GITHUB_STEP_SUMMARY;
  if (summaryPath == null || summaryPath === '') {
    return;
  }

  appendFileSync(
    summaryPath,
    [
      '### Release version',
      '',
      `- releaseTag: ${values.release_tag}`,
      `- versionName: ${values.version_name}`,
      `- buildNumber: ${values.build_number}`,
      `- Google Play versionCode: ${values.google_play_version_code}`,
      `- Apple CFBundleShortVersionString: ${values.apple_marketing_version}`,
      `- Apple CFBundleVersion: ${values.apple_build_number}`,
      '',
    ].join('\n')
  );
}

function writeReleaseInfo(values) {
  const gitSha = process.env.GITHUB_SHA ?? 'local';
  const outputPath = path.join(process.cwd(), 'packages/farm-core/src/releaseInfo.ts');

  writeFileSync(
    outputPath,
    [
      '// Generated by scripts/resolve-release-version.mjs.',
      'export const RELEASE_INFO = {',
      `  releaseTag: '${values.release_tag}',`,
      `  versionName: '${values.version_name}',`,
      `  major: ${values.release_major},`,
      `  minor: ${values.release_minor},`,
      `  patch: ${values.release_patch},`,
      `  buildNumber: ${values.build_number},`,
      `  gitSha: '${gitSha}',`,
      '} as const;',
      '',
    ].join('\n'),
    'utf8'
  );
}

try {
  const args = parseArgs(process.argv.slice(2));
  const values = resolveReleaseVersion(args);

  if (args.get('github-output')) {
    writeGithubOutput(values);
  }

  if (args.get('github-step-summary')) {
    writeGithubStepSummary(values);
  }

  if (args.get('write-release-info')) {
    writeReleaseInfo(values);
  }

  if (!args.get('quiet')) {
    console.log(JSON.stringify(values, null, 2));
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
