#!/usr/bin/env node
// GA4 Measurement Protocol API secret(비밀값)을 빌드 시 AIT 소스에 주입한다.
//
// apps/ait/src/firebaseWeb/mpSecret.generated.ts 는 빈 placeholder로 커밋되어 있고,
// 배포 워크플로가 이 스크립트를 실행해 환경변수 GA4_MP_API_SECRET 값으로 덮어쓴다.
// (중앙 binding projection이 releaseInfo.ts를 덮어쓰는 것과 동일한 패턴)
//
// 값이 비어 있으면 아무것도 하지 않는다(로컬/개발 빌드는 전송 no-op 상태를 유지).
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const secret = process.env.GA4_MP_API_SECRET ?? '';

if (secret === '') {
  console.warn(
    '[write-ait-mp-config] GA4_MP_API_SECRET 미설정 — mpSecret.generated.ts 를 그대로 둡니다(전송 no-op).',
  );
  process.exit(0);
}

if (!/^[A-Za-z0-9_-]+$/.test(secret)) {
  // GA4 MP secret 은 URL-safe 토큰이다. 예상치 못한 문자는 생성 파일 오염/주입을 막기 위해 거부한다.
  console.error('[write-ait-mp-config] GA4_MP_API_SECRET 형식이 올바르지 않습니다.');
  process.exit(1);
}

const outputPath = path.join(process.cwd(), 'apps/ait/src/firebaseWeb/mpSecret.generated.ts');

writeFileSync(
  outputPath,
  [
    '// Generated by scripts/write-ait-mp-config.mjs.',
    '//',
    '// GA4 Measurement Protocol API secret(비밀값)은 저장소에 커밋하지 않는다. 이 파일은',
    '// 빈 placeholder로 커밋되고, 배포 빌드에서 GA4_MP_API_SECRET 환경변수 값으로 덮어써진다.',
    '// (releaseInfo.ts와 동일한 "커밋된 placeholder를 빌드가 덮어쓰기" 패턴)',
    '//',
    '// 값이 비어 있으면 measurementProtocol 전송이 완전 no-op이 되어(로컬/개발 안전),',
    "// 자체 지표 서버 seam(SELF_METRICS_ENDPOINT='')과 동일하게 동작한다.",
    `export const GA4_MP_API_SECRET = '${secret}';`,
    '',
  ].join('\n'),
);

console.log('[write-ait-mp-config] mpSecret.generated.ts 주입 완료.');
