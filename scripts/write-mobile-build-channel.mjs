#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const validChannels = new Set(['internal', 'production']);

function parseArgs(argv) {
  const args = new Map();

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg.startsWith('--')) {
      throw new Error(`Unexpected argument: ${arg}`);
    }

    const key = arg.slice(2);
    const value = argv[index + 1];
    if (value == null || value.startsWith('--')) {
      throw new Error(`Missing value for --${key}`);
    }

    args.set(key, value);
    index += 1;
  }

  return args;
}

try {
  const args = parseArgs(process.argv.slice(2));
  const channel = args.get('channel') ?? process.env.MOBILE_BUILD_CHANNEL ?? 'production';

  if (!validChannels.has(channel)) {
    throw new Error(`Unsupported mobile build channel: ${channel}`);
  }

  const outputPath = path.join(process.cwd(), 'apps/mobile/src/buildChannel.ts');
  fs.writeFileSync(
    outputPath,
    [
      '// Generated by scripts/write-mobile-build-channel.mjs.',
      `export type MobileBuildChannel = 'internal' | 'production';`,
      '',
      `export const MOBILE_BUILD_CHANNEL = '${channel}' as MobileBuildChannel;`,
      '',
      `export const isInternalTestBuild = MOBILE_BUILD_CHANNEL === 'internal';`,
      '',
    ].join('\n'),
    'utf8'
  );

  console.log(`Mobile build channel: ${channel}`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
