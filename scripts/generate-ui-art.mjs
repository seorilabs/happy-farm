import { Buffer } from 'node:buffer';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// 게임 UI 스킨과 아이콘(#606)을 두 호스트로 옮긴다. 원본은 scripts/build-ui-art.py가 만든
// assets/art/ui/runtime/이다. mobile은 Metro 정적 import로, AIT는 Granite가 로컬 require 자산을
// 읽지 못하고 원격 이미지는 첫 렌더에 깜빡이므로 base64로 넣는다(타이틀 아트와 같은 이유).
// --check는 두 호스트의 사본이 원본과 같은지만 확인한다(CI).
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const runtimeDir = path.join(root, 'assets/art/ui/runtime');
const nativeDir = path.join(root, 'apps/mobile/src/art/assets');
const mobileTarget = path.join(root, 'apps/mobile/src/art/uiArt.generated.ts');
const aitTarget = path.join(root, 'apps/ait/src/farm/platform/uiArt.generated.ts');
const check = process.argv.includes('--check');

const manifest = JSON.parse(fs.readFileSync(path.join(runtimeDir, 'manifest.json'), 'utf8'));
const skinKeys = Object.keys(manifest.skins);
const parts = ['left', 'center', 'right'];
const files = [
  ...skinKeys.flatMap((key) => parts.map((part) => `ui_skin_${key}_${part}.png`)),
  ...manifest.icons.map((key) => `ui_icon_${key}.png`),
];

const failures = [];
function writeOrCheck(target, content) {
  if (check) {
    if (!fs.existsSync(target) || !Buffer.from(content).equals(fs.readFileSync(target))) {
      failures.push(path.relative(root, target));
    }
  } else {
    fs.writeFileSync(target, content);
  }
}

const dataUri = {};
for (const file of files) {
  const bytes = fs.readFileSync(path.join(runtimeDir, file));
  writeOrCheck(path.join(nativeDir, file), bytes);
  dataUri[file] = `data:image/png;base64,${bytes.toString('base64')}`;
}

// 디스플레이 서체(scripts/build-display-font.py 결과)를 iOS 리소스와 Android assets/fonts로 복사한다.
// iOS는 PostScript 이름, Android는 파일 이름으로 찾으므로 둘 다 Baloo2-ExtraBold다.
const fontSource = fs.readFileSync(path.join(root, 'assets/fonts/Baloo2-ExtraBold.ttf'));
for (const dir of ['apps/mobile/src/fonts', 'apps/mobile/android/app/src/main/assets/fonts']) {
  if (!check) fs.mkdirSync(path.join(root, dir), { recursive: true });
  writeOrCheck(path.join(root, dir, 'Baloo2-ExtraBold.ttf'), fontSource);
}

const identifier = (file) => file.replace(/\.png$/, '');
const mobileSource = [
  '// Generated by scripts/generate-ui-art.mjs. Source: assets/art/ui/runtime',
  "import type { FarmUiArt } from '../../../../packages/farm-ui/src';",
  '',
  ...files.map((file) => `import ${identifier(file)} from './assets/${file}';`),
  '',
  'export const mobileUiArt: FarmUiArt = {',
  '  icons: {',
  ...manifest.icons.map((key) => `    ${key}: ui_icon_${key},`),
  '  },',
  '  skins: {',
  ...skinKeys.map(
    (key) =>
      `    ${key}: { left: ui_skin_${key}_left, center: ui_skin_${key}_center, right: ui_skin_${key}_right, capRatio: ${manifest.skins[key].capRatio} },`
  ),
  '  },',
  '};',
  '',
].join('\n');
writeOrCheck(mobileTarget, mobileSource);

const aitArt = {
  icons: Object.fromEntries(manifest.icons.map((key) => [key, { uri: dataUri[`ui_icon_${key}.png`] }])),
  skins: Object.fromEntries(
    skinKeys.map((key) => [
      key,
      {
        left: { uri: dataUri[`ui_skin_${key}_left.png`] },
        center: { uri: dataUri[`ui_skin_${key}_center.png`] },
        right: { uri: dataUri[`ui_skin_${key}_right.png`] },
        capRatio: manifest.skins[key].capRatio,
      },
    ])
  ),
};
const aitSource = `// Generated by scripts/generate-ui-art.mjs. Source: assets/art/ui/runtime\nimport type { FarmUiArt } from '../../../../../packages/farm-ui/src';\n\nexport const appsInTossUiArt: FarmUiArt = ${JSON.stringify(aitArt)};\n`;
writeOrCheck(aitTarget, aitSource);

if (failures.length > 0) {
  throw new Error(`UI art copies differ from assets/art/ui/runtime: ${failures.join(', ')}`);
}
console.log(`UI art: mobile assets and AIT embedded images match (${files.length} files, AIT ${Math.round(aitSource.length / 1024)}KB).`);
